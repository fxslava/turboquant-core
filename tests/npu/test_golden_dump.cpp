struct DecodeGeometry {
    std::uint32_t requests, context, heads, kv_heads, dim, page, max_blocks, physical_pages;
    std::uint32_t splits, heads_per_task;
    float scale, inv_sqrt_len;
};

fd::Launch derive_launch(const DecodeGeometry& g, bool raw_entry, unsigned output_stage)
{
    fd::Launch config;
    config.element_type = 1;  // BF16: the only instance the operator carries
    config.tokens = g.requests;
    config.kv_heads = g.kv_heads;
    config.heads = g.heads;
    config.block_size = g.page;
    config.max_blocks = g.max_blocks;
    config.splits = g.splits;
    config.heads_per_task = g.heads_per_task;
    config.fused_context_limit = 4096;
    config.scale = g.scale;
    config.inv_sqrt_len = g.inv_sqrt_len;
    const unsigned group = g.heads / g.kv_heads;
    const unsigned chunk = std::min(g.heads_per_task, group);
    const unsigned tasks = g.requests * g.kv_heads * g.splits * ((group + chunk - 1) / chunk);
    config.tasks_per_block = (tasks + 31) / 32;
    config.grid = (tasks + config.tasks_per_block - 1) / config.tasks_per_block;
    config.reduce_tasks_per_block = (g.requests * g.heads + config.grid - 1) / config.grid;
    if (raw_entry) {
        const unsigned vectors = g.requests * g.heads;
        config.prologue_vectors_per_block = (vectors + config.grid - 1) / config.grid;
        config.prologue_cube_chunk_vectors = 0;
        config.output_stage = output_stage;
    }
    require(fd::valid_launch(config.grid, config.tokens, config.heads, config.kv_heads,
                             config.head_size, config.block_size, config.max_blocks,
                             config.splits, config.heads_per_task, config.tasks_per_block,
                             config.reduce_tasks_per_block),
            "the dump's geometry does not satisfy valid_launch");
    return config;
}

// The ordered-integer ULP distance between two bf16 words.
int bf16_ulp(std::uint16_t a, std::uint16_t b)
{
    const auto order = [](std::uint16_t w) -> int {
        return (w & 0x8000u) ? -static_cast<int>(w & 0x7FFFu) : static_cast<int>(w & 0x7FFFu);
    };
    return std::abs(order(a) - order(b));
}

struct FloatDiff {
    int worst_ulp = 0;
    double worst_abs = 0.0;
    double worst_rel = 0.0;
    double scale_ratio = 0.0;  // sum(got*want)/sum(want*want): 1.0 unless a uniform factor is off
    double worst_row_rel = 0.0;  // |got - want| / row max|want|, the fp8-operand residual's unit
    std::size_t live = 0;
};

// The output image is [rows, 256] with rows = requests * heads. A channel passes on the bf16
// ULP budget or, failing that, on the row-relative budget -- the one comparison here that
// honestly has a tolerance, because the kernel accumulates in fp32 against a float64 reference
// and its Cube operands are fp8 e4m3.
FloatDiff compare_output(const char* what, const std::vector<std::uint8_t>& image, const Tensor& expected,
                         int ulp_budget, double rel_budget)
{
    const std::vector<float> want = typed<float>(expected);
    require(image.size() >= want.size() * 2, "output image is short");
    const std::size_t row_width = 256;  // fd::kHeadSize, the decode's one head size
    require(want.size() % row_width == 0, "output image is not a whole number of rows");
    FloatDiff diff;
    double dot = 0.0, norm = 0.0;
    for (std::size_t i = 0; i < want.size(); ++i) {
        std::uint16_t got_bits;
        std::memcpy(&got_bits, image.data() + 2 * i, 2);
        const double got = tq_test::bf16_to_float(got_bits);
        const double reference = static_cast<double>(want[i]);
        require(std::isfinite(got), "the kernel produced a non-finite output channel");
        const std::uint16_t want_bits = tq_test::float_to_bf16_rne(want[i]);
        const int ulp = bf16_ulp(got_bits, want_bits);
        const double absolute = std::fabs(got - reference);
        const double relative = absolute / std::fabs(reference);
        diff.worst_ulp = std::max(diff.worst_ulp, ulp);
        diff.worst_abs = std::max(diff.worst_abs, absolute);
        diff.worst_rel = std::max(diff.worst_rel, relative);
        dot += got * reference;
        norm += reference * reference;
        double row_max = 0.0;
        const std::size_t row = i / row_width * row_width;
        for (std::size_t c = 0; c < row_width; ++c)
            row_max = std::max(row_max, std::fabs(static_cast<double>(want[row + c])));
        const double row_rel = row_max > 0.0 ? absolute / row_max : absolute;
        diff.worst_row_rel = std::max(diff.worst_row_rel, row_rel);
        if (ulp <= ulp_budget || row_rel <= rel_budget) continue;
        if (diff.live < 4) {
            std::fprintf(stderr,
                         "  channel %zu: got %.9g (0x%04x) %s %.9g (0x%04x), %d bf16 ULP, "
                         "%.4f of the row max\n", i, got, got_bits, what, reference, want_bits, ulp,
                         row_rel);
        }
        ++diff.live;
    }
    diff.scale_ratio = norm > 0.0 ? dot / norm : 1.0;
    return diff;
}

int run_case(const std::string& case_dir, int ulp_budget, double rel_budget, camodel::Session& session)
{
    const Manifest dump = load_manifest(case_dir);
    require(dump.kernel == "decode", case_dir + " is not a decode dump");
    DecodeGeometry g;
    g.requests = static_cast<std::uint32_t>(dump.geo("requests"));
    g.context = static_cast<std::uint32_t>(dump.geo("context"));
    g.heads = static_cast<std::uint32_t>(dump.geo("num_heads"));
    g.kv_heads = static_cast<std::uint32_t>(dump.geo("num_kv_heads"));
    g.dim = static_cast<std::uint32_t>(dump.geo("head_size"));
    g.page = static_cast<std::uint32_t>(dump.geo("block_size"));
    g.max_blocks = static_cast<std::uint32_t>(dump.geo("max_blocks"));
    g.physical_pages = static_cast<std::uint32_t>(dump.geo("physical_pages"));
    g.splits = static_cast<std::uint32_t>(dump.geo("splits"));
    g.heads_per_task = static_cast<std::uint32_t>(dump.geo("heads_per_task"));
    g.scale = static_cast<float>(dump.scalar("scale"));
    g.inv_sqrt_len = static_cast<float>(dump.scalar("inv_sqrt_len"));

    const std::vector<std::int32_t> lengths = typed<std::int32_t>(dump.tensor("context_lens"));
    const std::vector<std::int32_t> table = typed<std::int32_t>(dump.tensor("block_table"));
    const std::size_t live_out = static_cast<std::size_t>(g.requests) * g.heads * g.dim;

    // Input allocations. The caches, the table, the lengths and the mode pool
    // are read-only; each is checked byte-identical after every leg.
    camodel::GuardedDeviceBuffer key_cache(dump.tensor("key_cache").size_bytes());
    camodel::GuardedDeviceBuffer value_cache(dump.tensor("value_cache").size_bytes());
    camodel::GuardedDeviceBuffer scale_cache(dump.tensor("scale_cache").size_bytes());
    camodel::GuardedDeviceBuffer table_buf((table.size() * 4 + 31) / 32 * 32);
    camodel::GuardedDeviceBuffer lengths_buf((lengths.size() * 4 + 31) / 32 * 32);
    camodel::GuardedDeviceBuffer mode_tables(dump.tensor("mode_tables").size_bytes());
    camodel::GuardedDeviceBuffer pi_signs(dump.tensor("pi_signs").size_bytes());
    camodel::GuardedDeviceBuffer rot_tables(dump.tensor("rot_tables").size_bytes());
    camodel::GuardedDeviceBuffer h16(dump.tensor("h16").size_bytes());
    camodel::GuardedDeviceBuffer raw_query(dump.tensor("raw_query").size_bytes());
    std::memcpy(key_cache.host_payload(), dump.tensor("key_cache").bytes.data(),
                dump.tensor("key_cache").size_bytes());
    std::memcpy(value_cache.host_payload(), dump.tensor("value_cache").bytes.data(),
                dump.tensor("value_cache").size_bytes());
    std::memcpy(scale_cache.host_payload(), dump.tensor("scale_cache").bytes.data(),
                dump.tensor("scale_cache").size_bytes());
    std::memcpy(table_buf.host_payload(), table.data(), table.size() * 4);
    std::memcpy(lengths_buf.host_payload(), lengths.data(), lengths.size() * 4);
    std::memcpy(mode_tables.host_payload(), dump.tensor("mode_tables").bytes.data(),
                dump.tensor("mode_tables").size_bytes());
    std::memcpy(pi_signs.host_payload(), dump.tensor("pi_signs").bytes.data(),
                dump.tensor("pi_signs").size_bytes());
    std::memcpy(rot_tables.host_payload(), dump.tensor("rot_tables").bytes.data(),
                dump.tensor("rot_tables").size_bytes());
    std::memcpy(h16.host_payload(), dump.tensor("h16").bytes.data(), dump.tensor("h16").size_bytes());
    std::memcpy(raw_query.host_payload(), dump.tensor("raw_query").bytes.data(),
                dump.tensor("raw_query").size_bytes());
    key_cache.upload();
    value_cache.upload();
    scale_cache.upload();
    table_buf.upload();
    lengths_buf.upload();
    mode_tables.upload();
    pi_signs.upload();
    rot_tables.upload();
    h16.upload();
    raw_query.upload();

    const std::vector<std::uint8_t> key_snapshot = dump.tensor("key_cache").bytes;
    const std::vector<std::uint8_t> value_snapshot = dump.tensor("value_cache").bytes;
    const std::vector<std::uint8_t> scale_snapshot = dump.tensor("scale_cache").bytes;

    const std::vector<std::uint8_t> query_rot_golden = dump.tensor("query_rot").bytes;

    struct Leg {
        bool raw_entry;
        unsigned stage;
        const char* expected;
        const char* name;
    };
    static const Leg kLegs[] = {
        {false, 0u, "expected_stage0", "pre-rotated"},
        {true, 0u, "expected_stage0", "raw-query/st0"},
        {true, 1u, "expected_stage1", "raw-query/st1"},
    };

    std::printf("decode golden dump %s: context %u, %u page(s), %u KV heads x %u = %u heads\n",
                case_dir.c_str(), g.context, g.max_blocks, g.kv_heads,
                g.heads / g.kv_heads, g.heads);
    int failures = 0;
    for (const Leg& leg : kLegs) {
        const fd::Launch config = derive_launch(g, leg.raw_entry, leg.stage);
        camodel::GuardedDeviceBuffer query_rot(query_rot_golden.size());
        camodel::GuardedDeviceBuffer workspace(
            static_cast<std::size_t>(g.requests) * g.heads * g.splits * (g.dim + 16) * 4 + 4096);
        camodel::GuardedDeviceBuffer output(live_out * 2 + 32);
        camodel::GuardedDeviceBuffer tiling(
            ascend_micro::fused_decode::decode_tiling_bytes_for(config));
        if (leg.raw_entry) {
            // The prologue writes this buffer; its content is checked after.
        } else {
            std::memcpy(query_rot.host_payload(), query_rot_golden.data(),
                        query_rot_golden.size());
        }
        query_rot.upload();
        {
            namespace fd_tiling = ascend_micro::fused_decode;
            std::vector<std::uint32_t> image(
                fd_tiling::decode_tiling_words(config.tokens, config.splits, config.grid), 0);
            const auto status = fd_tiling::build_decode_tiling(
                fd_tiling::decode_tiling_request(config), lengths.data(), table.data(),
                image.data());
            require(status == fd_tiling::DecodeTilingStatus::kOk,
                    fd_tiling::decode_tiling_status_text(status));
            std::memcpy(tiling.host_payload(), image.data(), image.size() * 4);
            tiling.upload();
        }

        const fd::Buffers buffers{query_rot.payload(),   key_cache.payload(),
                                  value_cache.payload(), scale_cache.payload(),
                                  table_buf.payload(),   lengths_buf.payload(),
                                  mode_tables.payload(), workspace.payload(),
                                  output.payload(),      tiling.payload()};
        std::printf("  launch  %-14s stage %u  grid %u  tiles context %u\n", leg.name, leg.stage,
                    config.grid, g.context);
        std::fflush(stdout);
        camodel::check(aclrtSynchronizeStream(session.stream), "pre-launch synchronize");
        if (leg.raw_entry) {
            const fd::RawQueryBuffers raw_buffers{raw_query.payload(), pi_signs.payload(),
                                                  rot_tables.payload(), h16.payload(), nullptr,
                                                  buffers};
            launch_fused_decode_opt_raw_query(session.stream, &config, &raw_buffers);
        } else {
            launch_fused_decode_opt(session.stream, &config, &buffers);
        }
        camodel::check(aclrtSynchronizeStream(session.stream), "post-launch synchronize");

        // The output against the fp64 golden. The same values are also checked
        // against the KV4_FP8 mode's own codec convention, so a disagreement is
        // NAMED -- a kernel that implements (code + 0.5) * scale / kGain is not
        // the writers' code * scale, and the two conventions are what this
        // runner exists to tell apart.
        output.download();
        output.assert_guards();
        const auto* out_image = static_cast<const std::uint8_t*>(output.host_payload());
        const std::vector<std::uint8_t> out_bytes{out_image, out_image + live_out * 2};
        const FloatDiff diff =
            compare_output("golden", out_bytes, dump.tensor(leg.expected), ulp_budget, rel_budget);
        const std::string kernel_expected =
            std::string("kernel_stage") + (leg.stage == 0 ? "0" : "1");
        const FloatDiff kernel_diff =
            compare_output("KV4_FP8 convention", out_bytes, dump.tensor(kernel_expected), ulp_budget, rel_budget);
        for (std::size_t i = live_out * 2; i < output.payload_bytes; ++i)
            require(out_image[i] == kGuardByteValue ||
                        out_image[i] == 0xAD || out_image[i] == 0xBE || out_image[i] == 0xEF,
                    "output tail canary clobbered");
        std::printf("    golden: worst %d bf16 ULP (budget %d), worst abs %.3e, worst "
                    "%.4f of row max (budget %.4f), scale ratio %.6f\n",
                    diff.worst_ulp, ulp_budget, diff.worst_abs, diff.worst_row_rel, rel_budget,
                    diff.scale_ratio);
        std::printf("    KV4_FP8 (code+0.5)/kGain convention: worst %d bf16 ULP, worst abs "
                    "%.3e, scale ratio %.6f%s\n",
                    kernel_diff.worst_ulp, kernel_diff.worst_abs, kernel_diff.scale_ratio,
                    kernel_diff.live == 0 && diff.live != 0
                        ? "  <-- the kernel implements THIS convention, not the golden's"
                        : "");
        if (diff.live != 0) {
            std::fprintf(stderr, "    %zu channels over budget against the golden\n",
                         diff.live);
            ++failures;
        }

        // The raw-query prologue's own product, bit-exact: its whole contract
        // is that it reproduces the pre-rotated query_rot exactly.
        if (leg.raw_entry) {
            query_rot.download();
            query_rot.assert_guards();
            const auto* got = static_cast<const std::uint8_t*>(query_rot.host_payload());
            if (!check_bit_exact("query_rot prologue",
                                 {got, got + query_rot_golden.size()}, query_rot_golden))
                ++failures;
        }

        // Every input allocation unchanged.
        key_cache.download();
        value_cache.download();
        scale_cache.download();
        table_buf.download();
        lengths_buf.download();
        mode_tables.download();
        pi_signs.download();
        rot_tables.download();
        h16.download();
        raw_query.download();
        key_cache.assert_guards();
        value_cache.assert_guards();
        scale_cache.assert_guards();
        table_buf.assert_guards();
        lengths_buf.assert_guards();
        mode_tables.assert_guards();
        tiling.assert_guards();
        require(std::memcmp(key_cache.host_payload(), key_snapshot.data(),
                            key_snapshot.size()) == 0,
                "the key cache changed under the decode");
        require(std::memcmp(value_cache.host_payload(), value_snapshot.data(),
                            value_snapshot.size()) == 0,
                "the value cache changed under the decode");
        require(std::memcmp(scale_cache.host_payload(), scale_snapshot.data(),
                            scale_snapshot.size()) == 0,
                "the scale cache changed under the decode");

        // S == 1 is the fused path: the Split-K workspace must be untouched.
        workspace.download();
        workspace.assert_guards();
        const auto* ws = static_cast<const std::uint32_t*>(workspace.host_payload());
        for (std::size_t i = 0; i < workspace.payload_bytes / 4; ++i)
            require(ws[i] == camodel::kCanary,
                    "the workspace was written on the fused (S=1) path");
    }
    require(failures == 0, "the decode disagrees with the PyTorch golden");
    std::printf("PASS decode %s: three legs against the fp64 PyTorch golden\n", case_dir.c_str());
    return 0;
}

