#if defined(TQ_GOLDEN_KERNEL_PREFILL)
// The scale plane, with the one diagnosed divergence allowed by name: the
// prefill kernel floors absmax at 1.0 before the exponent extraction
// (src/prefill/turboquant_reshape_batch.cpp, AscendC::Max(abs_max, abs_max,
// one, ...)), so an all-zero row stores 2^-6 there, where the PyTorch golden
// takes its explicit absmax == 0 branch and stores 1.0. The codes are zero on
// both sides, so the dequantised value is 0 either way -- immaterial, but a
// bit difference, and counted rather than hidden. Any OTHER scale mismatch
// fails the gate.
struct ScaleVerdict {
    std::size_t mismatched_floats = 0;
    std::size_t zero_row_floats = 0;
    std::size_t unexplained_floats = 0;
};

ScaleVerdict check_scale_plane(const std::uint8_t* got, const std::uint8_t* want,
                               std::size_t floats, bool nz_layout, int blocks, int heads,
                               int page, int dim, const std::uint8_t* want_key,
                               const std::uint8_t* want_value)
{
    ScaleVerdict verdict;
    const int packed = dim / 2;
    const int slot_floats = ((2 * heads + 7) / 8) * 8;
    for (std::size_t i = 0; i < floats; ++i) {
        if (std::memcmp(got + 4 * i, want + 4 * i, 4) == 0) continue;
        ++verdict.mismatched_floats;
        // Map the scale lane to its (plane, row) and ask whether the golden's
        // packed codes for that row are all zero.
        const std::uint8_t* plane = nullptr;
        bool zero_row = true;
        if (nz_layout) {
            const int slot = static_cast<int>(i) / slot_floats;
            const int lane = static_cast<int>(i) % slot_floats;
            const int head = lane % heads;
            const int kv = lane / heads;
            plane = kv == 0 ? want_key : want_value;
            if (kv > 1) zero_row = false;  // padding lane: not a row at all
            const int tile_row = slot % 64;
            const std::size_t row_base =
                static_cast<std::size_t>(slot - tile_row) * heads * packed +
                static_cast<std::size_t>(head) * 64 * packed + tile_row * 32;
            for (int g = 0; g < packed / 32 && zero_row; ++g)
                for (int b = 0; b < 32; ++b)
                    if (plane[row_base + static_cast<std::size_t>(g) * 64 * 32 + b] != 0)
                        zero_row = false;
        } else {
            const int plane_stride = blocks * heads * page;
            const int kv = static_cast<int>(i) / plane_stride;
            const int rest = static_cast<int>(i) % plane_stride;
            const int page_idx = rest / (heads * page);
            const int head = (rest % (heads * page)) / page;
            const int token = rest % page;
            plane = kv == 0 ? want_key : want_value;
            const std::size_t head_base =
                (static_cast<std::size_t>(page_idx) * heads + head) * page;
            if (kv == 0) {
                // Key plane, token-major: the row is `packed` consecutive bytes.
                const std::size_t base = (head_base + token) * packed;
                for (int b = 0; b < packed; ++b)
                    if (plane[base + b] != 0) zero_row = false;
            } else {
                // Value plane, channel-major inside the 16-token strip: the row
                // owns ONE nibble of every byte at a stride of 8 -- the other
                // nibble is a different token's lane and must be ignored.
                const int lane = token % 16;
                const std::size_t strip_base =
                    head_base * packed + static_cast<std::size_t>(token / 16) * (16 * packed);
                for (int c = 0; c < dim; ++c) {
                    const std::uint8_t byte =
                        plane[strip_base + static_cast<std::size_t>(c) * 8 + lane / 2];
                    const int code = lane % 2 == 0 ? byte & 0x0F : byte >> 4;
                    if (code != 0) zero_row = false;
                }
            }
        }
        if (zero_row) {
            // Accept only the exact diagnosed convention pair: the golden's
            // explicit absmax == 0 branch (1.0f) against the kernel's
            // absmax >= 1.0 floor (2^(0 - 2) / 16 = 2^-6). Anything else on a
            // zero row is a new divergence and fails like any other.
            float got_f, want_f;
            std::memcpy(&got_f, got + 4 * i, 4);
            std::memcpy(&want_f, want + 4 * i, 4);
            if (want_f == 1.0f && got_f == 0.015625f) {
                ++verdict.zero_row_floats;
                continue;
            }
        }
        if (verdict.unexplained_floats < 4) {
            std::uint32_t g, w;
            std::memcpy(&g, got + 4 * i, 4);
            std::memcpy(&w, want + 4 * i, 4);
            std::fprintf(stderr,
                         "  scale float %zu: device 0x%08x golden 0x%08x%s\n", i, g, w,
                         zero_row ? " on a zero row, but not the diagnosed 2^-6 vs 1.0 pair"
                                  : " on a NON-zero row");
        }
        ++verdict.unexplained_floats;
    }
    return verdict;
}
#endif  // TQ_GOLDEN_KERNEL_PREFILL

