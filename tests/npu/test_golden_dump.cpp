// GOLDEN DUMP COMPARISON: every kernel against the PyTorch golden model, on CAModel.
//
// The dumps under golden/dumps/ are generated by golden/generate_dumps.py from
// golden/turboquant_golden.py -- the standalone copy of vllm-ascend's PyTorch
// golden (turboquant_dry_run.py). Every operand the kernel reads comes out of
// the dump: the activations, the slot mapping, the LCG pi_signs, the BF16
// codec tables, h16 -- so what is compared here is the kernel against the
// PyTorch golden END TO END, not against a C++ re-statement of it.
//
// One binary per kernel, selected at compile time:
//
//   TQ_GOLDEN_KERNEL_PREFILL (+ TQ_GOLDEN_PREFILL_NZ 0/1)
//       the batch writer, strip or NZ-tiled build. BIT-EXACT comparison of
//       both packed planes and every scale float over the whole allocation:
//       the fixtures are integer-valued, so there is no rounding anywhere in
//       the path and no tolerance to hide a wrong byte behind.
//   TQ_GOLDEN_KERNEL_SCATTER
//       the AIV scatter writer, two sequential launches into one strip. The
//       second launch's bytes share their nibbles' bytes with the first
//       launch's tokens, so the read-modify-write is what step 2 checks.
//   TQ_GOLDEN_KERNEL_DECODE
//       the fused decode, three legs per case: the pre-rotated entry, the
//       raw-query entry at output_stage 0 and at output_stage 1. The fp64
//       golden attention is compared with two budgets: --ulp-budget in bf16
//       ULP (default 8), and --rel-budget as a fraction of the row's max
//       magnitude (default 0.08); a channel passes on EITHER. The relative
//       half exists because the pipeline rounds its Cube operands to fp8
//       e4m3: the dump's query is built so the query operand is exact
//       (+-448 everywhere), but the softmax probabilities are rounded, and
//       that leaves a few-percent-of-row-max residual no fixture escapes.
//       The raw-query prologue's own output (query_rot) is compared BIT-EXACT.
//
//   --dump-root DIR   where golden/dumps lives (default "golden/dumps")
//   --case NAME       one case directory instead of the kernel's default list
//   --ulp-budget N    decode only (default 8)
//   --rel-budget R    decode only (default 0.08, of the row's max magnitude)

